#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const geographyDir = path.join(root, "research/geography");
const output = path.join(root, "website/app/geography-data.ts");

async function readJsonl(file) {
  const text = await readFile(file, "utf8");
  return text
    .split(/\r?\n/)
    .filter((line) => line.trim())
    .map((line, index) => {
      try {
        return JSON.parse(line);
      } catch (error) {
        throw new Error(`${file}:${index + 1}: ${error.message}`);
      }
    });
}

const [places, events, people, sources] = await Promise.all([
  readJsonl(path.join(geographyDir, "places.jsonl")),
  readJsonl(path.join(geographyDir, "events.jsonl")),
  readJsonl(path.join(root, "research/people/people.jsonl")),
  readJsonl(path.join(root, "research/sources/sources.jsonl")),
]);

function uniqueIds(items, label) {
  const ids = new Set();
  for (const item of items) {
    if (!item.id || ids.has(item.id)) {
      throw new Error(`${label} contains a missing or duplicate id: ${item.id}`);
    }
    ids.add(item.id);
  }
  return ids;
}

const placeIds = uniqueIds(places, "places.jsonl");
const eventIds = uniqueIds(events, "events.jsonl");
const peopleIds = uniqueIds(people, "people.jsonl");
const sourceIds = uniqueIds(sources, "sources.jsonl");

for (const place of places) {
  if (
    !Array.isArray(place.coordinates) ||
    place.coordinates.length !== 2 ||
    !place.coordinates.every(Number.isFinite)
  ) {
    throw new Error(`${place.id} has invalid coordinates`);
  }
  if (place.parent_ref && !placeIds.has(place.parent_ref)) {
    throw new Error(`${place.id} references unknown parent ${place.parent_ref}`);
  }
  if (!place.precision || !place.coordinate_source?.url) {
    throw new Error(`${place.id} is missing precision or coordinate provenance`);
  }
}

for (const event of events) {
  if (!placeIds.has(event.place_ref)) {
    throw new Error(`${event.id} references unknown place ${event.place_ref}`);
  }
  for (const personRef of event.person_refs ?? []) {
    if (!peopleIds.has(personRef)) {
      throw new Error(`${event.id} references unknown person ${personRef}`);
    }
  }
  for (const evidenceRef of event.evidence_refs ?? []) {
    if (!sourceIds.has(evidenceRef)) {
      throw new Error(`${event.id} references unknown source ${evidenceRef}`);
    }
  }
  if (!event.date && !event.date_range) {
    throw new Error(`${event.id} needs a date or date_range`);
  }
  if (!event.map_groups?.length || !Number.isFinite(event.sequence)) {
    throw new Error(`${event.id} needs map_groups and a numeric sequence`);
  }
}

const generated = `// Generated by tools/build-geography.mjs from research/geography/*.jsonl.
// Edit the JSONL ledgers, then rerun the generator.

export const geographyPlaces = ${JSON.stringify(places, null, 2)} as const;

export const geographyEvents = ${JSON.stringify(events, null, 2)} as const;
`;

await writeFile(output, generated);
console.log(
  `Validated ${placeIds.size} places and ${eventIds.size} events; wrote ${output}`,
);
